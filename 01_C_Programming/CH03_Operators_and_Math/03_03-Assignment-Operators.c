
#include <stdio.h>

int main()
{
	int a = 25;

	printf("The value of a is %d\n",a);
	a += 5;
	printf("The value of a is %d\n",a);
	a -= 5;
	printf("The value of a is %d\n",a);
	a *= 5;
	printf("The value of a is %d\n",a);
	a /= 5;
	printf("The value of a is %d\n",a);

	return(0);
}


//Different Types of Assignment Operators
// +=   - Addition
// -=   - Subtraction
// *=   - Multiplication
// /=   - Division
// %=   - Modulo
// <<=  - Bitshift Left
// >>=  - Bitshift Right
// &=   - Bitwise AND
// ^=   - Bitwise OR
